import { execFileSync } from "node:child_process";
import fs from "node:fs";
import path from "node:path";

const extensionRoot = path.resolve(import.meta.dirname, "..");
const repoRoot = path.resolve(extensionRoot, "..", "..");
const rootGoModule = fs
  .readFileSync(path.join(repoRoot, "go.mod"), "utf8")
  .match(/^module\s+(\S+)/m)?.[1];
if (!rootGoModule) throw new Error("Cannot determine the root Go module path");
const outputRoot = path.join(extensionRoot, "third_party_licenses");
const marker = path.join(outputRoot, ".generated-by-collect-licenses");

if (fs.existsSync(outputRoot)) {
  if (!fs.existsSync(marker)) {
    throw new Error(`Refusing to replace an unmanaged directory: ${outputRoot}`);
  }
  fs.rmSync(outputRoot, { recursive: true });
}
fs.mkdirSync(outputRoot, { recursive: true });
fs.writeFileSync(marker, "Generated by scripts/collect-licenses.mjs.\n");

const rows = [];
const npmLicenses = JSON.parse(
  execFileSync("pnpm", ["licenses", "list", "--prod", "--json"], {
    cwd: extensionRoot,
    encoding: "utf8",
  }),
);

for (const [license, packages] of Object.entries(npmLicenses)) {
  for (const dependency of packages) {
    const version = dependency.versions[0];
    const sourceRoot = dependency.paths[0];
    const targetRoot = path.join(outputRoot, "npm", dependency.name, version);
    const files = copyLegalFiles(sourceRoot, targetRoot);
    if (files.length === 0) {
      if (license !== "MIT") {
        throw new Error(`Missing license file for ${dependency.name}@${version} (${license})`);
      }
      // These packages declare MIT in package.json but omit its text from the npm tarball.
      const author = String(dependency.author || dependency.name);
      fs.mkdirSync(targetRoot, { recursive: true });
      fs.writeFileSync(path.join(targetRoot, "LICENSE-MIT.txt"), mitLicense(author));
      files.push("LICENSE-MIT.txt");
    }
    rows.push({
      name: `npm ${dependency.name}@${version}`,
      license:
        license === "Unknown" && dependency.name === "khroma"
          ? "MIT (included license file)"
          : license,
      source: dependency.homepage || `https://www.npmjs.com/package/${dependency.name}`,
      files: files.map((file) => path.posix.join("npm", dependency.name, version, file)),
    });
  }
}

const targetGOOS = process.env.ASP_LSP_SERVER_GOOS || process.env.GOOS;
const targetGOARCH = process.env.ASP_LSP_SERVER_GOARCH || process.env.GOARCH;
const goModules = execFileSync(
  "go",
  [
    "list",
    "-deps",
    "-f",
    "{{if .Module}}{{.Module.Path}}\t{{.Module.Version}}\t{{.Module.Dir}}{{end}}",
    "./cmd/asp-lsp-go",
  ],
  {
    cwd: repoRoot,
    encoding: "utf8",
    env: {
      ...process.env,
      ...(targetGOOS ? { GOOS: targetGOOS === "win32" ? "windows" : targetGOOS } : {}),
      ...(targetGOARCH ? { GOARCH: targetGOARCH === "x64" ? "amd64" : targetGOARCH } : {}),
    },
  },
);
for (const line of new Set(goModules.trim().split("\n"))) {
  if (!line) continue;
  const [name, version, sourceRoot] = line.split("\t");
  if (name === rootGoModule) continue;
  if (!name || !sourceRoot) throw new Error(`Invalid Go module record: ${line}`);
  const targetRoot = path.join(outputRoot, "go", name);
  const files = copyLegalFiles(sourceRoot, targetRoot);
  if (files.length === 0) throw new Error(`Missing license file for Go module ${name}`);
  rows.push({
    name: `Go ${name}${version ? `@${version}` : ""}`,
    license: "See included license",
    source: `https://${name.replace(/\/v\d+$/, "")}`,
    files: files.map((file) => path.posix.join("go", name, file)),
  });
}

rows.sort((a, b) => a.name.localeCompare(b.name));
const index = [
  "# Runtime dependency licenses",
  "",
  "Generated from the production pnpm dependency graph and the Go server's imported modules.",
  "Only runtime dependencies are listed; build tools are not shipped in the VSIX.",
  "For npm packages that declare MIT but omit its text, LICENSE-MIT.txt contains",
  "the standard MIT terms and the author named in the package metadata.",
  "",
  "| Dependency | License | Source | Included legal files |",
  "| --- | --- | --- | --- |",
  ...rows.map(
    ({ name, license, source, files }) =>
      `| ${name} | ${license} | <${source}> | ${files.map((file) => `[${path.posix.basename(file)}](<${file}>)`).join(", ")} |`,
  ),
  "",
];
fs.writeFileSync(path.join(outputRoot, "INDEX.md"), index.join("\n"));

function copyLegalFiles(sourceRoot, targetRoot) {
  const files = fs
    .readdirSync(sourceRoot, { withFileTypes: true })
    .filter(
      (entry) => entry.isFile() && /^(?:licen[cs]e|copying|notice)(?:[.\-_].*|$)/i.test(entry.name),
    )
    .map((entry) => entry.name);
  if (files.length) fs.mkdirSync(targetRoot, { recursive: true });
  for (const file of files)
    fs.copyFileSync(path.join(sourceRoot, file), path.join(targetRoot, file));
  return files;
}

